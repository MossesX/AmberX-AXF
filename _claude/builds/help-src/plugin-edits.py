n = 0
for folder, edits in EDITS.items():
    p = os.path.join(ROOT, "apps/console-web/plugins", folder, "help.json")
    if not os.path.exists(p): continue
    pack = json.load(open(p))
    for x in pack["data"]["entries"]:
        if x["target"] in edits:
            v = edits[x["target"]]
            x["title"], x["text"] = v[0], v[1]
            if len(v) > 2: x["kind"] = v[2]
            x.pop("draft", None); n += 1
    json.dump(pack, open(p, "w"), indent=2, ensure_ascii=False); open(p, "a").write("\n")
print(n, "entries edited")
