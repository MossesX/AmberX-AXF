#!/usr/bin/env node
/**
 * lib/amberx-core.gen.mjs = the notes core of the Notes and tasks plugin with the types stripped (esbuild), so the
 * runner (Node, no TypeScript loader) applies the AmberX notes core's own rules. `--check` fails when it is stale (test.mjs).
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, PLUGIN_DIR } from './lib/common.mjs';

const SRC = join(ROOT, 'apps/console-web/plugins/notes-tasks/web/notes/core.ts'); // axf-plugin:notes-tasks
const OUT = join(PLUGIN_DIR, 'lib/amberx-core.gen.mjs');
const bins = [join(ROOT, 'apps/console-web/node_modules/.bin/esbuild'), join(ROOT, 'apps/amberx-droid/node_modules/.bin/esbuild')];
const bin = bins.find(existsSync);
const HEAD = '// GENERATED by gen-amberx-core.mjs from the notes core of the Notes and tasks plugin. Do not edit; run node apps/console-web/plugins/token-control/gen-amberx-core.mjs\n';

function build() {
  const src = readFileSync(SRC, 'utf8');
  const js = bin
    ? execFileSync(bin, ['--loader=ts', '--format=esm', '--target=es2022'], { input: src, encoding: 'utf8' })
    : execFileSync('npx', ['-y', 'esbuild@0.24.0', '--loader=ts', '--format=esm', '--target=es2022'], { input: src, encoding: 'utf8' });
  return HEAD + js;
}

const next = build();
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== next) { console.error('lib/amberx-core.gen.mjs is stale: run node apps/console-web/plugins/token-control/gen-amberx-core.mjs'); process.exit(1); }
  console.log('amberx-core.gen.mjs up to date');
} else { writeFileSync(OUT, next); console.log(`wrote ${OUT}`); }
