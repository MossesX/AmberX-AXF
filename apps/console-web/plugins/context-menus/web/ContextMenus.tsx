/*
 * Context menus — the page. Generate (level, app, page → Claude → a draft to preview), Drafts (preview per zone, what
 * changes, Apply / Discard), Menus (every menu on the hub with Preview, Use, Edit, Restore, Delete) and Zones (the
 * registry, linked to the UI Manager's elements when that plugin is on). Layout only in CSS; every control is a
 * framework control and every colour / size comes from the asset tokens.
 */
import { useCallback, useEffect, useMemo, useState } from 'react';
import { Button, Container, MenuList, Note, SelectField, TabGroup, TextField, useEditorSync, useRuntime } from '@console/axf/react';
import { DataGrid, type GridColumn, type GridGroup } from '@console/axf/libs/datagrid';
import { EmptyState } from '@console/emptyState';
import * as R from '@console/axf/core/engines/context-menus-rules.mjs';
import type { CtxItem, LevelId, MenuDoc } from '@console/axf/core/engines/context-menus-rules.mjs';
import * as S from './store';

type Tab = 'generate' | 'drafts' | 'menus' | 'zones';
const LEVEL_OPTIONS = Object.values(R.LEVELS).map((l) => ({ value: l.id, label: `${l.label} · ≤${l.perTarget} items` }));

export function ContextMenusPage({ focus }: { focus?: { tab?: Tab; level?: LevelId; menu?: string } } = {}) {
  const rt = useRuntime();
  const [, bump] = useState(0);
  const [tab, setTab] = useState<Tab>(focus?.tab ?? 'generate');
  useEffect(() => S.subscribe(() => bump((n) => n + 1)), []);
  const refresh = useCallback(() => { void S.load(rt); }, [rt]);
  useEditorSync({ onRefresh: refresh });
  useEffect(() => { if (!S.getState()) refresh(); void S.reportZones(rt); }, [rt, refresh]);
  const s = S.getState();
  const err = S.getError();
  return (
    <div className="fx-stack fx-stack--lg axp-ctxm">
      <header className="fx-pagehead">
        <div>
          <p className="fx-eyebrow">Design &amp; branding</p>
          <h1>Context menus</h1>
          <p className="fx-muted">Every right-click menu of the app, kept once on axHub and generated by Claude at the coder level you pick.</p>
        </div>
        <div className="fx-row axp-ctxm-head">
          {s && <span className={`fx-chip ${s.onHub ? 'is-success' : ''}`} title={s.store}>{s.onHub ? 'One true source: axHub' : 'Local store (no hub mounted)'}</span>}
          <Button size="sm" icon="refresh" busy={S.isLoading()} onClick={refresh}>Refresh</Button>
        </div>
      </header>
      {err && <Note tone="warning">{err}</Note>}
      <TabGroup<Tab> id="context-menus.tabs" label="Context menus sections" value={tab} onChange={setTab} tabs={[
        { value: 'generate', label: 'Generate', icon: 'sparkles' },
        { value: 'drafts', label: 'Drafts', icon: 'eye', badge: s?.drafts.length ?? 0 },
        { value: 'menus', label: 'Menus', icon: 'menu', badge: s?.menus.length ?? 0 },
        { value: 'zones', label: 'Zones', icon: 'target', badge: s?.zones.length ?? 0 },
      ]} />
      {tab === 'generate' && <Generate level={focus?.level} onDraft={() => setTab('drafts')} />}
      {tab === 'drafts' && <Drafts />}
      {tab === 'menus' && <Menus focusMenu={focus?.menu} />}
      {tab === 'zones' && <Zones />}
    </div>
  );
}

/* ---------------- Generate ---------------- */

function Generate({ level: initial, onDraft }: { level?: LevelId; onDraft: () => void }) {
  const rt = useRuntime();
  const s = S.getState();
  const [level, setLevel] = useState<LevelId>(initial ?? 'pro');
  const [app, setApp] = useState(S.APP);
  const [page, setPage] = useState('');
  const [name, setName] = useState('');
  const [busy, setBusy] = useState(false);
  const [msg, setMsg] = useState<{ tone: 'info' | 'warning' | 'danger' | 'success'; text: string } | null>(null);
  const [prompt, setPrompt] = useState<string>('');
  const claude = s?.claude;
  const ready = !!claude?.ready;
  const l = R.LEVELS[level];
  const run = async () => {
    setBusy(true); setMsg(null);
    try {
      const r = await S.generate(level, { app, page, name, actions: liveActionsFor(rt) });
      if (!r.ok) { setMsg({ tone: r.aiMissing ? 'warning' : 'danger', text: r.error ?? 'Claude did not answer' }); return; }
      await S.load(rt);
      setMsg({ tone: 'success', text: `Draft ready (${r.model || 'Claude'}): ${r.draft?.summary.targets ?? 0} zones, ${r.draft?.summary.items ?? 0} items${r.draft?.warnings.length ? `, ${r.draft.warnings.length} warning(s)` : ''}. Preview it under Drafts, then Apply.` });
      onDraft();
    } catch (e) { setMsg({ tone: 'danger', text: e instanceof Error ? e.message : String(e) }); } finally { setBusy(false); }
  };
  const showPrompt = async () => {
    try { const r = await S.api.call<{ prompt: { system: string; messages: { content: string }[] } }>(`prompt?level=${level}&app=${encodeURIComponent(app)}&page=${encodeURIComponent(page)}`); setPrompt(`${r.prompt.system}\n\n${r.prompt.messages[0]?.content ?? ''}`); } catch (e) { setMsg({ tone: 'danger', text: e instanceof Error ? e.message : String(e) }); }
  };
  return (
    <Container title="Generate with Claude" icon="sparkles">
      <div className="fx-stack">
        {claude && !ready && <Note tone="warning"><strong>Claude is not ready.</strong> {claude.reason}</Note>}
        <div className="axp-ctxm-form">
          <SelectField label="Coder level" value={level} options={LEVEL_OPTIONS} onChange={(v) => setLevel(v as LevelId)} hint={l.brief} />
          <SelectField label="App" value={app} options={(s?.apps ?? [S.APP]).map((a) => ({ value: a, label: a }))} onChange={setApp} hint="The level can differ per app and page." />
          <TextField label="Page (optional)" value={page} onChange={setPage} placeholder="blank = the whole app" hint="One page's zones only." />
          <TextField label="Menu name (optional)" value={name} onChange={setName} placeholder={`${l.label} context menus · ${app}`} />
        </div>
        <div className="fx-row axp-ctxm-actions">
          <Button icon="sparkles" tone="primary" disabled={!ready} busy={busy} title={ready ? 'Spends Claude tokens; you preview before anything is applied' : claude?.reason} onClick={() => void run()}>Generate {l.label.toLowerCase()} menus</Button>
          <Button size="sm" icon="file-text" onClick={() => void showPrompt()}>Show the prompt (zero tokens)</Button>
          <Button size="sm" icon="refresh" onClick={() => void S.claudeCheck(true).then((c) => { const st = S.getState(); if (st) { st.claude = c; } setMsg({ tone: c.ready ? 'success' : 'warning', text: c.ready ? 'Claude answers: ready to generate.' : c.reason }); })}>Check Claude</Button>
        </div>
        {msg && <Note tone={msg.tone}>{msg.text}</Note>}
        <p className="fx-muted axp-ctxm-fine">Zones mapped at this level: {R.zonesForLevel(level, s?.zones ?? []).length} of {s?.zones.length ?? 0}. Items per zone: at most {l.perTarget}; the rest fold under More…. Submenus: {l.depth} deep. {l.developer ? 'Developer actions included.' : 'No developer jargon.'}</p>
        {prompt && <TextField label="The prompt Claude gets" value={prompt} onChange={() => undefined} rows={12} mono />}
      </div>
    </Container>
  );
}

function liveActionsFor(rt: ReturnType<typeof useRuntime>) { const acts = S.liveActions(rt); return acts.length ? acts : undefined; }

/* ---------------- Drafts: preview before applying ---------------- */

function Drafts() {
  const rt = useRuntime();
  const s = S.getState();
  const [busy, setBusy] = useState('');
  const [msg, setMsg] = useState('');
  const drafts = s?.drafts ?? [];
  if (!drafts.length) return <EmptyState icon="eye">No draft waiting. Generate one at a level, then preview it here before applying.</EmptyState>;
  const act = async (id: string, fn: () => Promise<unknown>, done: string) => { setBusy(id); setMsg(''); try { await fn(); await S.load(rt); setMsg(done); } catch (e) { setMsg(e instanceof Error ? e.message : String(e)); } finally { setBusy(''); } };
  return (
    <div className="fx-stack">
      {msg && <Note tone="info">{msg}</Note>}
      {drafts.map((d) => (
        <Container key={d.id} title={`${d.menu.name} · ${R.LEVELS[d.level].label}`} icon="eye">
          <div className="fx-stack">
            <p className="fx-muted axp-ctxm-fine">{d.app}{d.page ? ` · ${d.page}` : ''} · {d.summary.targets} zones · {d.summary.items} items · depth {d.summary.depth} · {d.model || 'Claude'} · {new Date(d.at).toLocaleString()}</p>
            {d.warnings.length > 0 && <Note tone="warning"><strong>{d.warnings.length} dropped or filled:</strong> {d.warnings.slice(0, 6).join(' · ')}{d.warnings.length > 6 ? ` · +${d.warnings.length - 6}` : ''}</Note>}
            <MenuPreview doc={d.menu} />
            <Diff diff={d.diff} />
            <div className="fx-row axp-ctxm-actions">
              <Button tone="primary" icon="check" busy={busy === d.id} onClick={() => void act(d.id, () => S.applyDraft(d.id, true), `${d.menu.name} applied and in use.`)}>Apply and use</Button>
              <Button size="sm" icon="save" busy={busy === d.id} onClick={() => void act(d.id, () => S.applyDraft(d.id, false), `${d.menu.name} saved; the app keeps its current menu.`)}>Save without switching</Button>
              <Button size="sm" tone="danger" icon="trash" confirm="Discard this draft?" undoable={false} busy={busy === d.id} onClick={() => void act(d.id, () => S.discardDraft(d.id), 'Draft discarded.')}>Discard</Button>
            </div>
          </div>
        </Container>
      ))}
    </div>
  );
}

function Diff({ diff }: { diff: R.TargetDiff[] }) {
  const changed = diff.filter((d) => d.status !== 'same');
  if (!changed.length) return <p className="fx-muted axp-ctxm-fine">No change against the menu in force.</p>;
  return (
    <details className="axp-ctxm-diff">
      <summary>What changes against the menu in force: {changed.length} zone(s)</summary>
      <ul className="axp-ctxm-list">
        {changed.map((d) => (
          <li key={d.target}><strong>{d.target}</strong> <span className="fx-muted">{d.status}</span>
            {d.added.length > 0 && <div className="axp-ctxm-diff__add">+ {d.added.join(' · ')}</div>}
            {d.removed.length > 0 && <div className="axp-ctxm-diff__del">− {d.removed.join(' · ')}</div>}
          </li>
        ))}
      </ul>
    </details>
  );
}

/** The real menu renderer on the draft's items, one zone at a time. */
function MenuPreview({ doc }: { doc: MenuDoc }) {
  const targets = Object.keys(doc.asset.data.targets);
  const [zone, setZone] = useState(targets[0] ?? 'default');
  const items = (doc.asset.data.targets[zone] ?? []) as unknown as Parameters<typeof MenuList>[0]['items'];
  useEffect(() => { if (!targets.includes(zone)) setZone(targets[0] ?? 'default'); }, [targets, zone]);
  return (
    <div className="axp-ctxm-preview">
      <SelectField label="Zone" value={zone} options={targets.map((t) => ({ value: t, label: `${t} · ${R.countItems(doc.asset.data.targets[t] as CtxItem[])} items` }))} onChange={setZone} />
      <div className="fx-ctx fx-popover axp-ctxm-preview__menu" role="presentation" data-fx-ctx-ignore="">
        {items.length ? <MenuList items={items} onDone={() => undefined} showIcons={doc.asset.data.showIcons} showShortcuts={doc.asset.data.showShortcuts} /> : <p className="fx-muted axp-ctxm-fine">Empty zone: the default menu shows here.</p>}
      </div>
    </div>
  );
}

/* ---------------- Menus: every menu on the hub ---------------- */

function Menus({ focusMenu }: { focusMenu?: string }) {
  const rt = useRuntime();
  const s = S.getState();
  const [q, setQ] = useState('');
  const [level, setLevel] = useState('');
  const [expanded, setExpanded] = useState<string[]>(focusMenu ? [focusMenu] : []);
  const [msg, setMsg] = useState('');
  const menus = useMemo(() => R.filterMenus(s?.menus ?? [], { q, level }), [s, q, level]);
  const groups = useMemo<GridGroup<MenuDoc>[]>(() => {
    const byApp = new Map<string, MenuDoc[]>();
    for (const m of menus) byApp.set(m.app, [...(byApp.get(m.app) ?? []), m]);
    return [...byApp.entries()].map(([app, rows]) => ({ id: app, title: app, icon: 'box', rows, groups: [], counts: `${rows.length}` }));
  }, [menus]);
  const act = async (fn: () => Promise<unknown>, done: string) => { setMsg(''); try { await fn(); await S.load(rt); setMsg(done); } catch (e) { setMsg(e instanceof Error ? e.message : String(e)); } };
  const columns: GridColumn<MenuDoc>[] = [
    { id: 'name', label: 'Menu', width: 'minmax(0, 3fr)', fixed: true, sortable: true, sortValue: (m) => m.name, render: (m) => <span className="axp-ctxm-name">{m.active && <span className="fx-chip is-success">in use</span>}{m.name}<span className="fx-muted axp-ctxm-id">{m.id}</span></span> },
    { id: 'level', label: 'Level', width: 'minmax(0, 1fr)', sortable: true, sortValue: (m) => R.LEVELS[m.level].order, render: (m) => R.LEVELS[m.level].label },
    { id: 'zones', label: 'Zones', width: 'minmax(0, 1fr)', align: 'end', sortable: true, sortValue: (m) => R.summarize(m).targets, render: (m) => R.summarize(m).targets },
    { id: 'items', label: 'Items', width: 'minmax(0, 1fr)', align: 'end', sortable: true, sortValue: (m) => R.summarize(m).items, render: (m) => R.summarize(m).items },
    { id: 'source', label: 'Made by', width: 'minmax(0, 1.4fr)', render: (m) => `${m.source}${m.model ? ` · ${m.model}` : ''}${m.by ? ` · ${m.by}` : ''}` },
    { id: 'updated', label: 'Updated', width: 'minmax(0, 1.4fr)', sortable: true, sortValue: (m) => m.updatedAt, render: (m) => new Date(m.updatedAt).toLocaleString() },
    { id: 'use', label: '', width: 'auto', render: (m) => <Button size="sm" icon="check" disabled={m.active} onClick={(e) => { e.stopPropagation(); void act(() => S.useMenu(m.id), `${m.name} is now the context menu of ${m.app}.`); }}>Use</Button> },
  ];
  return (
    <div className="fx-stack">
      <div className="axp-ctxm-form">
        <TextField label="Search" type="search" value={q} onChange={setQ} placeholder="name, zone, action, level…" />
        <SelectField label="Level" value={level} options={LEVEL_OPTIONS} onChange={setLevel} empty="Every level" />
      </div>
      {msg && <Note tone="info">{msg}</Note>}
      {menus.length === 0 ? <EmptyState icon="menu" compact>{s?.menus.length ? 'No menu matches.' : 'No context menu on the hub yet. Generate one, or save one from the designer.'}</EmptyState> : (
        <DataGrid<MenuDoc> id="context-menus" label="Context menus" groups={groups} columns={columns} rowId={(m) => m.id} rowLabel={(m) => m.name} hidden={[]}
          expanded={expanded} onToggleExpand={(id) => setExpanded((x) => (x.includes(id) ? x.filter((y) => y !== id) : [...x, id]))}
          onRowClick={(m) => setExpanded((x) => (x.includes(m.id) ? x.filter((y) => y !== m.id) : [...x, m.id]))}
          rowTone={(m) => (m.active ? 'success' : 'muted')}
          renderDetail={(m) => <MenuDetail doc={m} onDone={(t) => void act(async () => undefined, t)} />} />
      )}
    </div>
  );
}

function MenuDetail({ doc, onDone }: { doc: MenuDoc; onDone: (msg: string) => void }) {
  const rt = useRuntime();
  const [mode, setMode] = useState<'preview' | 'edit' | 'history'>('preview');
  const [text, setText] = useState(() => JSON.stringify(doc.asset.data.targets, null, 1));
  const [err, setErr] = useState('');
  const [history, setHistory] = useState<R.History | null>(null);
  useEffect(() => { if (mode === 'history' && !history) void S.historyOf(doc.id).then((r) => setHistory(r.history)).catch((e: Error) => setErr(e.message)); }, [mode, history, doc.id]);
  const save = async () => {
    setErr('');
    let targets: unknown;
    try { targets = JSON.parse(text); } catch { setErr('Not valid JSON.'); return; }
    const next = R.normalizeMenu({ ...doc, asset: { ...doc.asset, data: { ...doc.asset.data, targets } } });
    const errors = R.validateMenu(next);
    if (errors.length) { setErr(errors.join('; ')); return; }
    try { await S.saveMenu(doc.id, next); await S.load(rt); onDone(`${doc.name} saved (the previous version is a snapshot).`); setMode('preview'); } catch (e) { setErr(e instanceof Error ? e.message : String(e)); }
  };
  return (
    <div className="fx-stack axp-ctxm-detail">
      <div className="fx-row axp-ctxm-actions">
        <Button size="sm" icon="eye" tone={mode === 'preview' ? 'primary' : 'neutral'} onClick={() => setMode('preview')}>Preview</Button>
        <Button size="sm" icon="edit" tone={mode === 'edit' ? 'primary' : 'neutral'} onClick={() => setMode('edit')}>Edit</Button>
        <Button size="sm" icon="history" tone={mode === 'history' ? 'primary' : 'neutral'} onClick={() => setMode('history')}>Restore</Button>
        <Button size="sm" icon="sparkles" onClick={() => rt.dispatch(`context-menus.generate:${doc.level}:${doc.app}`)}>Regenerate at this level</Button>
        <Button size="sm" tone="danger" icon="trash" confirm={`Delete "${doc.name}" from the hub?`} undoable={false} onClick={() => void S.deleteMenu(doc.id).then(() => S.load(rt)).then(() => onDone(`${doc.name} deleted.`)).catch((e: Error) => setErr(e.message))}>Delete</Button>
      </div>
      {err && <Note tone="danger">{err}</Note>}
      {mode === 'preview' && <MenuPreview doc={doc} />}
      {mode === 'edit' && (
        <div className="fx-stack">
          <TextField label="Zones and items (JSON: zone → items; an item has id, label, icon, action, shortcut, items)" value={text} onChange={setText} rows={16} mono />
          <div className="fx-row axp-ctxm-actions"><Button tone="primary" icon="save" onClick={() => void save()}>Save</Button><Button size="sm" onClick={() => { setText(JSON.stringify(doc.asset.data.targets, null, 1)); setErr(''); }}>Reset</Button></div>
        </div>
      )}
      {mode === 'history' && (
        history?.versions.length ? (
          <ul className="axp-ctxm-list">
            {[...history.versions].reverse().map((v) => (
              <li key={v.v} className="fx-row axp-ctxm-hist">
                <span>v{v.v} · {new Date(v.at).toLocaleString()} · {v.by || '—'} · {R.summarize(v.doc).items} items</span>
                <Button size="sm" icon="history" onClick={() => void S.restoreMenu(doc.id, v.v).then(() => S.load(rt)).then(() => onDone(`${doc.name} restored to v${v.v}.`)).catch((e: Error) => setErr(e.message))}>Restore</Button>
              </li>
            ))}
          </ul>
        ) : <p className="fx-muted axp-ctxm-fine">No snapshot yet: one is kept every time the menu is saved again.</p>
      )}
    </div>
  );
}

/* ---------------- Zones ---------------- */

function Zones() {
  const rt = useRuntime();
  const s = S.getState();
  const [q, setQ] = useState('');
  const ui = S.uiElements();
  const zones = (s?.zones ?? []).filter((z) => !q || `${z.id} ${z.label} ${z.owner.id} ${z.pages.join(' ')} ${z.elements.join(' ')}`.toLowerCase().includes(q.toLowerCase()));
  const covered = new Set(Object.keys((s?.menus.find((m) => m.id === s.active[S.APP]) ?? s?.menus[0])?.asset.data.targets ?? {}));
  return (
    <div className="fx-stack">
      <p className="fx-muted axp-ctxm-fine">Every right-click zone the code draws, with its owner and the pages that showed it. {ui ? 'The UI Manager is on: a zone opens there.' : 'Turn the UI Manager plugin on to open a zone’s elements.'}</p>
      <div className="fx-row axp-ctxm-actions">
        <TextField label="Filter zones" type="search" value={q} onChange={setQ} placeholder="zone, plugin, page…" />
        <Button size="sm" icon="refresh" onClick={() => void S.api.call('zones?scan=true').then(() => S.load(rt))}>Rescan the code</Button>
        <Button size="sm" icon="target" onClick={() => void S.reportZones(rt).then(() => S.load(rt))}>Report this screen</Button>
      </div>
      {zones.length === 0 ? <EmptyState icon="target" compact>No zone matches.</EmptyState> : (
        <ul className="axp-ctxm-zones">
          {zones.map((z) => (
            <li key={z.id} className="axp-ctxm-zone" data-fx-ctx-target="context-menus-zone" data-fx-ctx-payload={z.id}>
              <div className="axp-ctxm-zone__head">
                <strong>{z.id}</strong>
                <span className={`fx-chip ${z.weight === 'core' ? 'is-accent' : ''}`}>{z.weight}</span>
                {covered.has(z.id) && <span className="fx-chip is-success">mapped</span>}
                <span className="fx-muted">{z.owner.kind}{z.owner.id && z.owner.kind !== 'framework' ? `: ${z.owner.id}` : ''}</span>
              </div>
              <div className="fx-muted axp-ctxm-fine">{z.label}{z.note ? ` · ${z.note}` : ''}{z.pages.length ? ` · pages: ${z.pages.join(', ')}` : ''}{z.elements.length ? ` · elements: ${z.elements.join(', ')}` : ''}</div>
              {ui?.open && <div className="fx-row axp-ctxm-actions"><Button size="sm" icon="sliders" onClick={() => ui.open?.(z.elements[0] ?? z.id)}>Open in the UI Manager</Button></div>}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
