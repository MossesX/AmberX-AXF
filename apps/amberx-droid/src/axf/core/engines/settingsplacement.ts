export type PickSource = 'screen' | 'owner' | 'plugin' | 'interface' | 'app' | 'legacy' | 'system';
export const PICK_SOURCE_LABELS: Record<PickSource, string> = {
  screen: 'set for this screen',
  owner: 'the plugin\'s own pick',
  plugin: 'the plugin\'s declared default',
  interface: 'the settings interface says so',
  app: 'the app default',
  legacy: 'the plugin opens in a dialog',
  system: 'the default',
};

export interface PickInputs {
  /** the screen's override (setting `axf.settingsPlacement.screen.<view>`) */
  screen?: unknown;
  /** the owner plugin's own pick (`axf.settingsPlacement.<owner>`) */
  owner?: unknown;
  /** plugin@1 `settingsPlacement` */
  declared?: unknown;
  /** the settings interface asset's `opensIn` (settings-ui@1) */
  interface?: unknown;
  /** `axf.settingsPlacement.default` (an app's manifest may seed it) */
  appDefault?: unknown;
  /** the owner's "Opens in" (placement@1): dialog → a dialog */
  legacyOpens?: string | null;
}

/** The pick in force, most specific scope first, and which scope it came from. Each scope's value is normalized on the one below it. */
export function pickFor(i: PickInputs): { pick: SettingsPlacementPick; from: PickSource } {
  const legacy = i.legacyOpens === 'dialog';
  let pick: SettingsPlacementPick = legacy ? { placement: 'dialog', side: 'right', mode: 'inline', looks: {} } : DEFAULT_PICK;
  let from: PickSource = legacy ? 'legacy' : 'system';
  const layer = (v: unknown, src: PickSource) => { if (hasPlacement(v)) { pick = normalizePick(v, pick); from = src; } };
  layer(i.appDefault, 'app');
  layer(i.interface, 'interface');
  layer(i.declared, 'plugin');
  layer(i.owner, 'owner');
  layer(i.screen, 'screen');
  return { pick, from };
}

/** The pick in force for a plugin (no screen): its own, else the app default, else its declared default, else the legacy rule. Kept for callers of the first contract. */
export function effectivePick(own: unknown, appDefault: unknown, legacyOpens?: string | null, declared?: unknown, iface?: unknown): SettingsPlacementPick {
  return pickFor({ owner: own, appDefault, legacyOpens, declared, interface: iface }).pick;
}

/** A settings interface asset's `opensIn` (settings-ui@1): a pick, or null when the asset says nothing. */
export function normalizeOpensIn(raw: unknown): SettingsPlacementPick | null {
  return hasPlacement(raw) ? normalizePick(raw) : null;
}

/* ---------------- resolving one opening ---------------- */

/** What the screen offers for `inside` (its <SettingsHost>), and what the screen allows right now. */
export interface HostInfo {
  /** in-screen modes the mounted host renders (always includes `pane`) */
  modes: readonly InsideMode[];
  /** the host is narrow (phone / compact window): split and drop-down don't fit */
  compact: boolean;
}

export type FallbackReason = 'not-open' | 'no-host' | 'unsupported' | 'compact';

export const FALLBACK_LABELS: Record<FallbackReason, string> = {
  'not-open': 'the screen isn\'t open, so they slide in as a side panel',
  'no-host': 'this screen has no room for them yet, so they slide in as a side panel',
  unsupported: 'the screen doesn\'t offer that, so they slide out as a pane over it',
  compact: 'the screen is too narrow for that, so they slide out as a pane over it',
};

/** Where one opening lands. */
export type SettingsRoute =
  | { via: 'page' }
  | { via: 'window'; look: SettingsLook }
  | { via: 'dialog'; look: SettingsLook }
  /** a side panel over the page (also the fallback when `inside` is impossible) */
  | { via: 'panel'; side: Side; look: SettingsLook; fallback?: FallbackReason }
  /** a bottom sheet over the page */
  | { via: 'sheet'; look: SettingsLook }
  /** inside the screen's mounted host */
  | { via: 'host'; mode: InsideMode; look: SettingsLook; fallback?: FallbackReason };

const MODES_FITTING_COMPACT: readonly InsideMode[] = ['pane', 'tab', 'inline'];

/**
 * Resolve one opening. `host` = the screen's mounted <SettingsHost> (null: none); `hostable` = a host exists for it at
 * all (mounted or not: a plugin that declares one, or a screen); `reducedMotion` turns every animation off.
 */
export function resolveSettingsOpen(pick: SettingsPlacementPick, ctx: { host: HostInfo | null; hostable: boolean; reducedMotion?: boolean }): SettingsRoute {
  const p = normalizePick(pick);
  const motion = (l: SettingsLook): SettingsLook => (ctx.reducedMotion ? { ...l, animation: 'none', speed: 'instant' } : l);
  const lookOf = (k: LookKey) => motion(normalizeLook(p.looks[k], k));
  if (p.placement === 'page') return { via: 'page' };
  if (p.placement === 'window') return { via: 'window', look: lookOf('window') };
  if (p.placement === 'dialog') return { via: 'dialog', look: lookOf('dialog') };
  if (p.placement === 'panel') return { via: 'panel', side: p.side, look: { ...lookOf('panel'), edge: p.side } };
  if (p.placement === 'sheet') return { via: 'sheet', look: { ...lookOf('sheet'), edge: 'bottom' } };
  // inside: the asked mode when it fits, else a pane over the host, else the side panel over the page
  const want = lookOf(`inside:${p.mode}`);
  const asPane = (): SettingsLook => {
    const pane = p.mode === 'pane' ? want : lookOf('inside:pane');
    return { ...pane, animation: pane.animation === 'none' || ctx.reducedMotion ? pane.animation : 'slide' };
  };
  if (!ctx.host) return { via: 'panel', side: p.side, look: { ...lookOf('panel'), edge: p.side }, fallback: ctx.hostable ? 'not-open' : 'no-host' };
  const modes = ctx.host.modes.includes('pane') ? ctx.host.modes : [...ctx.host.modes, 'pane' as const];
  if (!modes.includes(p.mode)) return { via: 'host', mode: 'pane', look: asPane(), fallback: 'unsupported' };
  if (ctx.host.compact && !MODES_FITTING_COMPACT.includes(p.mode)) return { via: 'host', mode: 'pane', look: asPane(), fallback: 'compact' };
  return { via: 'host', mode: p.mode, look: want };
}

/** plugin@1 `settingsHost`: `true` = every in-screen mode, a list = those (pane is always added), absent / false = none. */
export function hostModes(decl: unknown): InsideMode[] {
  if (decl === true) return [...INSIDE_MODES];
  const list = Array.isArray(decl) ? decl : decl && typeof decl === 'object' && Array.isArray((decl as { modes?: unknown }).modes) ? (decl as { modes: unknown[] }).modes : null;
  if (!list) return [];
  const out = INSIDE_MODES.filter((m) => list.includes(m));
  return out.length && !out.includes('pane') ? ['pane', ...out] : out;
}

/**
 * The look as CSS: custom properties the stylesheet (ui/axf.css, "Settings placement") reads, every one a theme token
 * or a share of the host, plus data attributes for the animation and edge.
 */
export function lookStyle(l: SettingsLook): { vars: Record<string, string>; attrs: Record<string, string> } {
  const ease: Record<Easing, string> = { theme: 'var(--fx-ease)', standard: 'ease', decelerate: 'ease-out', accelerate: 'ease-in', linear: 'linear', spring: 'cubic-bezier(0.34, 1.56, 0.64, 1)' };
  const level = (kind: 'radius' | 'shadow', v: Level) => (v === 'none' ? (kind === 'radius' ? '0' : 'none') : `var(--fx-${kind}-${v})`);
  return {
    vars: {
      '--axf-sp-dur': `calc(var(--fx-motion) * ${SPEED_FACTOR[l.speed]})`,
      '--axf-sp-ease': ease[l.easing],
      '--axf-sp-size': `${Math.round(SIZE_SHARE[l.size] * 100)}%`,
      '--axf-sp-radius': level('radius', l.radius),
      '--axf-sp-shadow': level('shadow', l.shadow),
      '--axf-sp-blur': l.blur ? 'var(--fx-blur)' : '0',
    },
    attrs: { 'data-axf-sp-anim': l.animation, 'data-axf-sp-edge': l.edge, 'data-axf-sp-pos': l.position, 'data-axf-sp-dim': l.dim ? 'on' : 'off' },
  };
}

/** One line on where the settings open, for lists and chips ("Side panel, left"; "Inside the screen · slide-out pane, left"). */
export function describePick(p: SettingsPlacementPick): string {
  const n = normalizePick(p);
  if (n.placement === 'panel') return CHOICE_LABELS[`panel-${n.side}`];
  if (n.placement !== 'inside') return PLACEMENT_LABELS[n.placement];
  const l = normalizeLook(n.looks[`inside:${n.mode}`], `inside:${n.mode}`);
  return `${PLACEMENT_LABELS.inside} · ${MODE_LABELS[n.mode].toLowerCase()}${n.mode === 'pane' ? `, ${l.edge}` : ''}`;
}

