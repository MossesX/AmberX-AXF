/* ---------------- normalizing ---------------- */

const one = <T extends string>(list: readonly T[], x: unknown, fallback: T): T => (typeof x === 'string' && (list as readonly string[]).includes(x) ? (x as T) : fallback);

export const lookKeyOf = (placement: SettingsPlacement, mode: InsideMode): LookKey | null =>
  placement === 'inside' ? `inside:${mode}` : placement === 'page' ? null : placement;

/** A stored look (partial, possibly stale) → a whole one, on `key`'s defaults. */
export function normalizeLook(x: unknown, key: LookKey): SettingsLook {
  const d = DEFAULT_LOOKS[key];
  const o = (x && typeof x === 'object' ? x : {}) as Record<string, unknown>;
  return {
    animation: one(ANIMATIONS, o.animation, d.animation),
    speed: one(SPEEDS, o.speed, d.speed),
    easing: one(EASINGS, o.easing, d.easing),
    edge: one(EDGES, o.edge, d.edge),
    size: one(SIZES, o.size, d.size),
    position: one(POSITIONS, o.position, d.position),
    dim: typeof o.dim === 'boolean' ? o.dim : d.dim,
    blur: typeof o.blur === 'boolean' ? o.blur : d.blur,
    radius: one(LEVELS, o.radius, d.radius),
    shadow: one(LEVELS, o.shadow, d.shadow),
  };
}

/**
 * A stored pick (object, JSON string or a placement word such as "dialog" / "side panel left") → a valid pick; unknown
 * values fall back. Older shapes load: `main` → page, a `fallback` look → the panel look, no `side` → right (or the old
 * page pane's edge when it was left or right).
 */
export function normalizePick(x: unknown, fallback: SettingsPlacementPick = DEFAULT_PICK): SettingsPlacementPick {
  let o: unknown = x;
  if (typeof x === 'string') {
    const t = x.trim();
    if (t.startsWith('{')) { try { o = JSON.parse(t); } catch { o = null; } }
    else o = parsePlacement(t) ?? null;
  }
  if (!o || typeof o !== 'object') return { ...fallback, looks: { ...fallback.looks } };
  const r = o as Record<string, unknown>;
  const looks: SettingsPlacementPick['looks'] = {};
  const src = (r.looks && typeof r.looks === 'object' ? r.looks : {}) as Record<string, unknown>;
  for (const [k, v] of Object.entries(src)) {
    const key = (k in DEFAULT_LOOKS ? k : LOOK_KEY_ALIASES[k]) as LookKey | undefined;
    if (key && v && typeof v === 'object' && !looks[key]) looks[key] = normalizeLook(v, key);
  }
  const placement = placementOf(r.placement) ?? fallback.placement;
  const legacyEdge = (src.fallback as { edge?: unknown } | undefined)?.edge;
  const side = one(SIDES, r.side, one(SIDES, legacyEdge, fallback.side));
  return { $axf: 'settings-placement@1', placement, side, mode: one(INSIDE_MODES, r.mode, fallback.mode), looks };
}

/** The pick to store (compact JSON). */
export const encodePick = (p: SettingsPlacementPick): string => JSON.stringify(normalizePick(p));

/** Is this stored value a pick at all (set), as opposed to absent / empty / "default"? */
export const isPickSet = (x: unknown): boolean => x != null && x !== '' && !(typeof x === 'string' && isDefaultWord(x));

/** Does this value name a placement (a pick object, its JSON, or words like "side panel left")? Anything else is skipped by the scopes. */
export function hasPlacement(x: unknown): boolean {
  if (!isPickSet(x)) return false;
  if (typeof x === 'string') {
    const t = x.trim();
    if (t.startsWith('{')) { try { return !!placementOf((JSON.parse(t) as { placement?: unknown })?.placement); } catch { return false; } }
    const p = parsePlacement(t);
    return p !== null && p !== 'default';
  }
  return typeof x === 'object' && !!placementOf((x as { placement?: unknown }).placement);
}

/* ---------------- plain choices (menus, selects, voice) ---------------- */

/** The choice a pick shows as. */
export const choiceOf = (p: SettingsPlacementPick): PlacementChoice => (p.placement === 'panel' ? `panel-${p.side}` : p.placement);

/** A choice applied to a pick (its looks and inside mode are kept). */
export function applyChoice(choice: PlacementChoice, base: SettingsPlacementPick = DEFAULT_PICK): SettingsPlacementPick {
  const b = normalizePick(base);
  const parts = choiceParts(choice);
  if (!parts) return b;
  return { ...b, placement: parts.placement, ...(parts.side ? { side: parts.side } : {}) };
}

/**
 * Free text ("side panel left", "bottom sheet", "in a dialog", "pop it up in a floating window") → a pick, or null when
 * no placement is named. "default" / "app default" → `'default'` (clear the override). The longest placement word in
 * the text wins; "left" / "right" pick the panel's side; an inside mode in the words ("inside as a split view") sets it.
 */
export function parsePlacement(text: unknown): SettingsPlacementPick | 'default' | null {
  const r = parsePlacementChoice(text);
  if (!r) return null;
  if (r === 'default') return 'default';
  const pick = applyChoice(r.choice);
  if (r.mode) pick.mode = r.mode;
  return pick;
}

