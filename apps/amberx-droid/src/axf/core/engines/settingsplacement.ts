/*
 * Settings placement engine (settings-placement@1, Nov 3 2026; revised Nov 4 2026 for every screen): where settings open
 * when a screen's gear, a plugin's "Settings" item, a search hit, `app.settings` or `settings.open:<tab>` asks for them.
 *
 * Brett, Nov 3 2026: "Plugins need to open their settings either in them or in a pop-up dialog as well as existing in
 * the main settings interface. … it needs one more to open in itself. And whenever it can't open within itself, it will
 * open a pane. A pane will slide out. You need to be able to configure the animation for each one too."
 * Brett, Nov 4 2026: "Set the settings interface for Molly to open in a dialog." … "I should be able to select in every
 * screen where its settings pops up." … "Every settings interface should have a setting to declare where it pops up."
 *
 * Placements (the words Brett used):
 *   dialog = a pop-up dialog over the page (position, size)
 *   panel  = a side panel that slides in over the page, from the left or the right (`side`)
 *   sheet  = a bottom sheet that slides up over the page
 *   inside = inside the screen itself: an inline section, a slide-out pane, a drop-down, a tab or a split view (`mode`);
 *            the screen's host (<SettingsHost>, react/settingsHost.tsx: every screen has one, a plugin may add its own)
 *   page   = the full settings page (what every settings opening did before; was `main`)
 *   window = its own floating window
 * Settings always stay on the settings page too; a placement only picks where an opening lands.
 *
 * Scopes, most specific first (`pickFor`): the per-screen override (setting `axf.settingsPlacement.screen.<view>`;
 * absent = "use the app default"), the owner plugin's own pick (`axf.settingsPlacement.<owner>`), the plugin's declared
 * default (plugin@1 `settingsPlacement`), the settings interface asset's own `opensIn` (settings-ui@1), the app default
 * (`axf.settingsPlacement.default`, an app may seed it in its manifest `settingsPlacement`), the legacy rule (owner's
 * "Opens in" = dialog → dialog), and last the system default: the page.
 *
 * Fallback: `inside` when the screen can't host it (no host mounted, the mode isn't one it offers, or a split / drop-down
 * on a compact screen) opens the side panel (`panel` look, the pick's side) over the page, or a pane over the host.
 *
 * Look: every placement has its own look (animation, speed, easing, edge, size, position, dim, blur, corner radius,
 * shadow). Every value is a name the stylesheet maps onto theme tokens (`--fx-motion`, `--fx-ease`, `--fx-radius-*`,
 * `--fx-shadow-*`, `--fx-blur`, `--fx-scrim`), never a raw size or colour; reduced motion turns every animation off.
 * Panels animate out the way they came in (react/settingsHost.tsx keeps a closing surface for one duration).
 *
 * Pure: the settings library (libs/settings) asks `resolveSettingsOpen` what to do and the React layer renders it.
 * Stored picks are JSON strings (`encodePick`); older picks (`main`, a `fallback` look, no `side`) still load.
 * Web only for now; the Kotlin twin is a deferred gap (framework/spec/PORTING.md). Fixture: spec/fixtures/settings-placement.json
 * (generated by spec/gen-settings-placement.mts, replayed by spec/check-settings-placement.mts).
 */

