/** Demo app registry: every demo app generated (or recorded) from the library picker. */
@Composable
fun DemosView() {
    val repo = rememberRepo() ?: return AxfEmptyState("Console data missing")
    val runtime = LocalAxfRuntime.current
    val demos by repo.demos.collectAsState()
    LazyColumn(Modifier.fillMaxWidth(), contentPadding = PaddingValues(Axf.space.two), verticalArrangement = Arrangement.spacedBy(Axf.space.one)) {
        item { AxfPageHead("Demo apps", eyebrow = "${demos.size} recorded", description = "One small app per library, generated by `axf new-demo` (apps/demo-<library>). Screenshots, APK links and deep-link launch arrive with the GitHub/VPS libraries.", actions = { AxfButton("Pick a library", { runtime.navigate("libraries") }, tone = ButtonTone.PRIMARY, icon = "box") }) }
        if (demos.isEmpty()) item { AxfEmptyState("No demo apps yet", message = "Open Libraries, pick one and tap Build library.") }
        for (d in demos.sortedByDescending { it.createdAt }) item(key = d.id) {
            AxfCard(title = d.name, icon = "play", actions = { AxfBadge(d.status, tone = if (d.status == "built") "success" else if (d.status == "scaffolded") "info" else "warning") }) {
                AxfText("apps/${d.id} · library ${d.library} · template ${d.template}", mono = true, muted = true)
                AxfText("created ${d.createdAt.take(19).replace('T', ' ')}", muted = true)
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    AxfButton("Launch", { runtime.toast("Deep-link launch (axf://${d.id}/home) needs the demo installed — wave 2.", ai.amberx.axf.kernel.runtime.ToastKind.INFO) }, icon = "external")
                    AxfButton("Screens", { runtime.toast("Screenshot gallery is a wave-2 capability.", ai.amberx.axf.kernel.runtime.ToastKind.INFO) }, icon = "image")
                }
            }
        }
    }
}

/** Modules & packages: live kernel modules + the Gradle module/package map from the tracker + ports registry. */
@OptIn(ExperimentalLayoutApi::class)
@Composable
fun ModulesView() {
    val repo = rememberRepo() ?: return AxfEmptyState("Console data missing")
    val kernel = LocalAxfKernel.current
    val runtime = LocalAxfRuntime.current
    val tracker by repo.tracker.collectAsState()
    var tab by remember { mutableStateOf("live") }
    val live = remember(kernel, kernel?.started) { kernel?.modules?.info() ?: emptyList() }
    val gradle = tracker.items.filter { it.tab == "modules" && it.parent == null }
    val packages = remember(live) { live.map { it.id }.filter { it.startsWith("ai.amberx.") }.groupBy { it.split('.').take(4).joinToString(".") } }
    LazyColumn(Modifier.fillMaxWidth(), contentPadding = PaddingValues(Axf.space.two), verticalArrangement = Arrangement.spacedBy(Axf.space.one)) {
        item { AxfPageHead("Modules & packages", eyebrow = "${live.size} live · ${gradle.size} gradle modules · ${Ports.ALL.size} ports", description = "Live kernel modules with state and dependencies, the Gradle module map with build status, the package tree, and the port registry.", actions = { AxfButton("Kernel status", { runtime.navigate("devtools") }, icon = "bug", requires = "dev.tools") }) }
        item { FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) { for ((id, l) in listOf("live" to "Live modules", "gradle" to "Gradle modules", "packages" to "Packages", "ports" to "Ports")) AxfChip(l, selected = tab == id, onClick = { tab = id }) } }
        when (tab) {
            "live" -> for (m in live) item(key = m.id) {
                AxfCard(title = m.label, icon = if (m.placeholder) "box" else "layers", actions = { AxfBadge(m.state.name.lowercase(), tone = when (m.state) { ModuleState.STARTED -> "success"; ModuleState.FAILED -> "danger"; else -> "accent" }); if (m.placeholder) AxfBadge("placeholder", tone = "warning") }) {
                    AxfText("${m.id} · v${m.version} · API ${m.apiLevel}", mono = true, muted = true)
                    if (m.dependsOn.isNotEmpty()) AxfText("depends on " + m.dependsOn.joinToString(), muted = true)
                    if (m.provides.isNotEmpty()) AxfText("provides " + m.provides.joinToString(), muted = true)
                    if (m.error != null) AxfText(m.error!!, color = Axf.colors.danger)
                }
            }
            "gradle" -> for (g in gradle) item(key = g.id) { AxfListItem(g.title.substringBefore(" — "), subtitle = g.title.substringAfter(" — ", "") + (g.module?.let { " · $it" } ?: ""), icon = if (g.tag == "lock") "lock" else "grid", trailing = { StatusBadge(repo.status(g.id)) }, onClick = { repo.setStatus(g.id, Status.entries[(repo.status(g.id).ordinal + 1) % Status.entries.size]) }) }
            "packages" -> for ((pkg, ids) in packages) { item(key = "p-$pkg") { AxfSectionHeader(pkg, accent = true) }; for (id in ids) item(key = id) { AxfListItem(id, icon = "folder", subtitle = "framework/android/${id.removePrefix("ai.amberx.axf.").let { if (it.contains('.')) it else if (it in setOf("settings", "logging", "admin", "accounts", "profile", "billing")) "lib-$it" else "axf-$it" }}") } }
            else -> for (p in Ports.ALL) item(key = p.id) { AxfListItem(p.label, subtitle = p.stack, icon = when (p.id) { "web" -> "cloud"; "android" -> "box"; else -> "flag" }, trailing = { AxfBadge(p.status.name.lowercase(), tone = when (p.status) { ai.amberx.axf.kernel.contract.PortStatus.BUILT -> "success"; ai.amberx.axf.kernel.contract.PortStatus.PLANNED -> "info"; else -> "warning" }) }) }
        }
    }
}
