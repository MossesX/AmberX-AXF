/**
 * The ONE emitter for `src/plugins/installed.generated.ts` — imported by the
 * runtime engine (`src/plugins/plugin-manager/engine.server.ts`, which
 * rewrites the loader on every import/uninstall/flip) and by `scripts/peel.mjs`
 * (which re-materialises a peeled app's installed plugins on a re-peel).
 *
 * Two writers, one template, deliberately: the loader is the file that makes
 * an installed plugin REAL, and two spellings of it would eventually disagree
 * about the shape `installPluginModules` receives. Plain `.mjs` with an
 * explicit extension because BOTH consumers must load it where they run — the
 * engine under Next's bundler, the peel under plain Node with type stripping,
 * where an extensionless import does not resolve.
 *
 * Zero dependencies, pure string building. The caller decides what the rows
 * are; this file only guarantees every loader ever written looks the same.
 */

/**
 * @param {{ id: string, specifier: string }[]} rows — one per ENABLED
 *   installed plugin; `specifier` is the extensionless relative import.
 * @param {string[]} skipped — ledger entries left out, with reasons, named in
 *   a comment rather than silently dropped.
 * @returns {string} the complete file content.
 */
export function loaderSource(rows, skipped = []) {
  const imports = rows.map((r, i) => `import * as p${i} from "${r.specifier}";`).join("\n");
  const list = rows.map((r, i) => `  { id: "${r.id}", mod: p${i} }`).join(",\n");
  const skippedNote = skipped.length
    ? `//\n// Skipped (in the ledger, unusable on disk): ${skipped.join(", ")}\n`
    : "";

  return `/**
 * @file GENERATED by the plugin engine — the imported-plugin loader.
 *
 * \`engine.server.ts\` (the Plugin Manager) rewrites this file when a package is
 * imported, uninstalled, enabled or disabled: one static import per ENABLED
 * imported plugin, so the bundler compiles exactly the plugins the ledger
 * (\`assets/registry.json\`) says are on. Do not edit by hand — the next
 * regeneration replaces the whole file. The committed state is the honest
 * empty: a fresh clone has imported nothing.
 *
 * Static imports rather than \`import()\` by design: a dynamic import of a
 * computed path is invisible to the bundler, to the closure resolver and to
 * every gate that reads this tree — the exact class of blind spot the
 * enforcement doctrine exists to prevent. The cost is that install/flip lands
 * at the next compile (the dev server does this on save; a compiled app on its
 * next build), and the engine SAYS so rather than pretending otherwise.
 *
 * The host's boot feeds this list to \`installPluginModules()\`
 * (\`./plugin-manager/install\`) — \`studio.subsystem.ts\` in the SDK, the
 * generated \`src/boot.ts\` in a peeled app.
 */
${skippedNote}${imports ? imports + "\n" : ""}
export interface InstalledPluginModule {
  /** The plugin's asset id — its directory under \`src/plugins/\`. */
  readonly id: string;
  /** The entry module's namespace object, whose exports get installed. */
  readonly mod: Readonly<Record<string, unknown>>;
}

export const INSTALLED_PLUGINS: readonly InstalledPluginModule[] = [${rows.length ? "\n" + list + "\n" : ""}];
`;
}
