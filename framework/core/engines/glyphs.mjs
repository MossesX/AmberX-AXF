/** The glyph a name draws: itself, its alias target, or null when the framework has no such glyph. */
export function glyphName(name) {
  const n = String(name ?? '');
  if (Object.hasOwn(GLYPHS, n)) return n;
  if (Object.hasOwn(GLYPH_ALIASES, n)) return GLYPH_ALIASES[n];
  return null;
}

/** The path data a name draws (the fallback box for an unknown name, like the Icon component). */
export function glyphPath(name) {
  return GLYPHS[glyphName(name) ?? GLYPH_FALLBACK];
}

