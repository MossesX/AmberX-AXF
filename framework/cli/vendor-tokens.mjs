#!/usr/bin/env node
/**
 * vendor-tokens — writes the framework's default --fx-* token sheet for an app that does not run the theme engines
 * (an imported app with a self-contained build context, e.g. one that vendors its own core).
 *
 *   node framework/cli/vendor-tokens.mjs <out.css>
 *
 * The sheet is generated, never hand-edited: framework/ui/axf.css's :root defaults (colours, fonts, radii, space,
 * border width, opacities) plus every scale token's default (typography@1, density@1, sizing@1, from
 * core/engines/scale-rules.mjs). Code in the app then reads tokens only (check-theme.mjs passes) and, once the app
 * runs the engines, the same names carry the live assets. Re-run after a token is added.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCALE_TYPES, scaleVars } from '../core/engines/scale-rules.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const out = process.argv[2];
if (!out) { console.error('usage: node framework/cli/vendor-tokens.mjs <out.css>'); process.exit(2); }

const css = readFileSync(join(ROOT, 'framework/ui/axf.css'), 'utf8');
const root = css.match(/:root\s*\{([\s\S]*?)\n\}/);
if (!root) { console.error('framework/ui/axf.css has no :root block'); process.exit(1); }
const base = root[1].split('\n').map((l) => l.replace(/\/\*.*?\*\//g, '').trim()).filter(Boolean);
const scale = [];
for (const t of SCALE_TYPES) for (const [k, v] of Object.entries(scaleVars(t, null))) scale.push(`${k}: ${v};`);

const body = `/* Generated by framework/cli/vendor-tokens.mjs — do not edit; re-run it instead.
   The framework's default --fx-* tokens, for an app that does not run the theme engines yet. */
:root {
  ${base.join('\n  ')}
  ${scale.join('\n  ')}
}
`;
mkdirSync(dirname(resolve(out)), { recursive: true });
writeFileSync(resolve(out), body);
console.log(`${out}: ${base.length} base line(s), ${scale.length} scale token(s)`);
