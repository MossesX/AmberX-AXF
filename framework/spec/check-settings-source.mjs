#!/usr/bin/env node
/**
 * settings-source@1 conformance: the registry is valid, owner lookups answer the fixture's golden rows (exact keys,
 * `*` and `**` patterns, unknown keys, ambiguity refused), pointer maths, and reads / writes go through the owner only
 * (a non-owner write, an unregistered key, a writer off the list and a browser store are refused).
 *   node framework/spec/check-settings-source.mjs           check
 *   node framework/spec/check-settings-source.mjs --write   regenerate fixtures/settings-sources.json
 * Python twin: apps/console-web/server/settings_source.py replays the same fixture (server tests).
 */
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as S from '../core/settings-source.mjs';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const FIX = join(ROOT, 'framework/spec/fixtures/settings-sources.json');
const WRITE = process.argv.includes('--write');
let n = 0;
const t = async (name, fn) => { try { await fn(); n += 1; } catch (e) { console.error(`✗ ${name}`); throw e; } };
const codeOf = (fn) => { try { const v = fn(); return v && typeof v.then === 'function' ? v.then(() => 'ok', (e) => { if (!(e instanceof S.SettingsSourceError)) throw e; return e.code; }) : 'ok'; } catch (e) { if (!(e instanceof S.SettingsSourceError)) throw e; return e.code; } };
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

const reg = S.loadRegistry();
const out = { $axf: 'settings-sources@1', note: 'Generated by framework/spec/check-settings-source.mjs --write; every port (settings-source.mjs, settings_source.py) answers the same owner for each key.' };

// ── 1. the real registry is valid and has no ambiguity ──
await t('registry valid', () => { assert.deepEqual(S.registryErrors(reg), []); });
out.stores = Object.keys(reg.stores);
out.entries = reg.settings.map((e) => ({ key: e.key, store: e.store, rank: S.rankOf(e.key) }));

// ── 2. golden owner lookups on the real registry ──
const LOOKUP_KEYS = ['accounts.mossesx-max-.use', 'accounts.account-3.fable', 'accounts.hulu0241.parallel', 'accounts.workers', 'accounts.buildAccount',
  'accounts.limits.building', 'accounts.api.mossesx-api.enabled', 'accounts.api.account-5.dailyCapUsd', 'pipeline.parallelPerAccount', 'pipeline.apiAccounts',
  'claude.builds.defaultModel', 'claude.noWait.enabled', 'appearance.skin', 'appearance.defaultSkin', 'appearance.tokens.axf.color.bg',
  'look.axf-console.skin.use', 'look.amberx-droid.own.spacing', 'nothing.here', 'accounts', 'pipeline', 'accountsx.a.use'];
out.lookups = LOOKUP_KEYS.map((key) => {
  const o = S.ownerOf(key, { registry: reg, env: { AXF_ROOT: '/repo', AXHUB_PROJECTS_DIR: '/projects' } });
  return { key, owner: o ? { entry: o.entry.key, store: o.store.id, storeKey: o.storeKey, pointer: o.pointer, captures: o.captures, file: o.file } : null };
});
await t('lookups resolve', () => {
  const by = Object.fromEntries(out.lookups.map((l) => [l.key, l.owner]));
  assert.equal(by['accounts.mossesx-max-.use'].pointer, '/perAccount/mossesx-max-/use');
  assert.equal(by['accounts.mossesx-max-.use'].store, 'claude-accounts/workers');
  assert.equal(by['accounts.workers'].pointer, '/workers');
  assert.equal(by['accounts.api.account-5.dailyCapUsd'].pointer, '/api/account-5/dailyCapUsd');
  assert.equal(by['claude.builds.defaultModel'].pointer, '/values/builds.defaultModel');
  assert.equal(by['look.axf-console.skin.use'].pointer, '/skin/use');
  assert.equal(by['look.axf-console.skin.use'].storeKey, 'settings/looks/axf-console.json');
  assert.equal(by['pipeline.parallelPerAccount'].file, '/projects/amberx-axf/_data/pipeline/settings.json');
  assert.equal(by['nothing.here'], null); assert.equal(by.accounts, null); assert.equal(by.pipeline, null); assert.equal(by['accountsx.a.use'], null);
});
await t('bad keys refused', () => { assert.equal(codeOf(() => S.ownerOf('Bad.Key')), 'invalid_key'); assert.equal(codeOf(() => S.ownerOf('a..b')), 'invalid_key'); assert.equal(codeOf(() => S.ownerOf('accounts.*.use')), 'invalid_key'); });

// ── 3. patterns, ranks, overlap, pointers ──
out.patterns = ['a.b', 'a.*', 'a.**', 'a.*.c', 'a.*.**', 'a.b.c.**'].map((p) => { const c = S.compilePattern(p); return { pattern: p, literals: c.literals, stars: c.stars, rest: c.rest, exact: c.exact, rank: S.rankOf(c) }; });
out.matches = [['a.*.c', 'a.x.c'], ['a.*.c', 'a.x.d'], ['a.**', 'a'], ['a.**', 'a.b.c'], ['a.*', 'a.b.c'], ['a.b', 'a.b'], ['a.*.**', 'a.x.y.z']].map(([p, k]) => ({ pattern: p, key: k, captures: S.matchKey(p, k) }));
out.overlaps = [['a.*', 'a.b'], ['a.*', 'b.*'], ['a.**', 'a.b.c'], ['a.b.**', 'a.*.c'], ['a.*.c', 'a.*.d'], ['a.b', 'a.b.c']].map(([x, y]) => ({ a: x, b: y, overlap: S.patternsOverlap(x, y) }));
await t('pattern maths', () => {
  const r = Object.fromEntries(out.patterns.map((p) => [p.pattern, p.rank]));
  assert.ok(r['a.b'] > r['a.*'] && r['a.*'] > r['a.**'] && r['a.*.c'] > r['a.*'] && r['a.b.c.**'] > r['a.**'] && r['a.*.**'] > r['a.**']);
  assert.deepEqual(out.matches[0].captures, { 1: 'x' }); assert.equal(out.matches[1].captures, null); assert.equal(out.matches[2].captures, null);
  assert.deepEqual(out.matches[3].captures, { rest: 'b.c' }); assert.equal(out.matches[4].captures, null); assert.deepEqual(out.matches[6].captures, { 1: 'x', rest: 'y.z' });
  assert.deepEqual(out.overlaps.map((o) => o.overlap), [true, false, true, true, false, false]);
});
const doc = { a: { b: 1, 'c.d': 2 }, list: [1, 2] };
out.pointers = { get: [S.getAt(doc, '/a/b'), S.getAt(doc, '/a/c.d'), S.getAt(doc, '/a/x'), S.getAt(doc, ''), S.getAt(doc, '/list/1')], set: S.setAt(doc, '/a/x/y', 3), del: S.deleteAt(doc, '/a/b'), delMissing: S.deleteAt(doc, '/q/r'), whole: S.setAt(doc, '', { z: 1 }), resolve: [S.resolvePointer('/p/{1}/q', { 1: 'x' }), S.resolvePointer('/v/{rest}', { rest: 'a.b' }), S.resolvePointer('/{rest/}', { rest: 'a.b' }), S.resolvePointer('/', {})] };
await t('pointer maths', () => {
  assert.deepEqual(out.pointers.get, [1, 2, undefined, doc, 2]);
  assert.deepEqual(out.pointers.set, { a: { b: 1, 'c.d': 2, x: { y: 3 } }, list: [1, 2] });
  assert.deepEqual(out.pointers.del, { a: { 'c.d': 2 }, list: [1, 2] }); assert.deepEqual(out.pointers.delMissing, doc);
  assert.deepEqual(out.pointers.resolve, ['/p/x/q', '/v/a.b', '/a/b', '']);
  assert.deepEqual(doc, { a: { b: 1, 'c.d': 2 }, list: [1, 2] });
});

// ── 4. registry validation: every error the check must catch ──
const base = () => ({ $axf: 'settings-sources@1', stores: { s: { kind: 'data-store', ns: 'console', path: 'x/s.json', owner: 'plugin:x' }, w: { kind: 'browser', storageKey: 'axf.settings.demo', owner: 'app:demo' } }, settings: [] });
const entry = (over = {}) => ({ key: 'x.a', store: 's', pointer: '/a', readers: [], writers: ['plugin:x'], mirrors: [], ...over });
out.registryErrors = {
  ok: S.registryErrors({ ...base(), settings: [entry(), entry({ key: 'x.*.b', pointer: '/{1}/b' }), entry({ key: 'x.**', pointer: '/all/{rest}' })] }),
  frame: S.registryErrors({ $axf: 'other@1' }),
  mirrors: S.registryErrors({ ...base(), settings: [entry({ mirrors: [{ store: 'w' }] })] }),
  unknownStore: S.registryErrors({ ...base(), settings: [entry({ store: 'nope' })] }),
  badKey: S.registryErrors({ ...base(), settings: [entry({ key: 'X.A' })] }),
  captureMissing: S.registryErrors({ ...base(), settings: [entry({ key: 'x.a', pointer: '/{1}' })] }),
  restMissing: S.registryErrors({ ...base(), settings: [entry({ key: 'x.**', pointer: '/all' })] }),
  twice: S.registryErrors({ ...base(), settings: [entry(), entry()] }),
  ambiguous: S.registryErrors({ ...base(), settings: [entry({ key: 'x.*.b', pointer: '/{1}/b' }), entry({ key: 'x.a.*', pointer: '/a/{1}' })] }),
  layered: S.registryErrors({ ...base(), settings: [entry({ key: 'x.a.b' }), entry({ key: 'x.*.b', pointer: '/{1}/b' }), entry({ key: 'x.**', pointer: '/{rest}' })] }),
  formerlyUnknown: S.registryErrors({ ...base(), settings: [entry({ formerly: [{ store: 'gone', pointer: '/a' }] })] }),
  storeKind: S.registryErrors({ ...base(), stores: { s: { kind: 'disk', owner: 'x' } }, settings: [] }),
  browserNoKey: S.registryErrors({ ...base(), stores: { w: { kind: 'browser', owner: 'x' } }, settings: [] }),
};
await t('registry errors', () => {
  assert.deepEqual(out.registryErrors.ok, []); assert.deepEqual(out.registryErrors.layered, []);
  for (const k of Object.keys(out.registryErrors)) if (k !== 'ok' && k !== 'layered') assert.ok(out.registryErrors[k].length, k);
  assert.match(out.registryErrors.ambiguous[0], /ambiguous/); assert.match(out.registryErrors.mirrors[0], /mirrors/);
});

// ── 5. reads and writes through the owner, on a temporary data root ──
const tmp = mkdtempSync(join(tmpdir(), 'axf-settings-source-'));
const env = { ...process.env, AXF_ROOT: tmp, AXHUB_PROJECTS_DIR: join(tmp, 'projects'), AXF_STATE: join(tmp, '.axf-console/state.json'), AXF_PLUGINS_DATA_DIR: join(tmp, '.axf-console/plugins') };
mkdirSync(join(tmp, '.axf-console/plugins/alpha'), { recursive: true }); mkdirSync(join(tmp, 'projects/amberx-axf/_data/beta'), { recursive: true });
const testReg = {
  $axf: 'settings-sources@1',
  stores: {
    'alpha/settings': { kind: 'data-store', ns: 'plugins', path: 'alpha/settings.json', frame: 'alpha-settings@1', owner: 'plugin:alpha', file: '{plugins}/alpha/settings.json' },
    'beta/settings': { kind: 'data-store', ns: 'console', path: 'beta/settings.json', owner: 'plugin:beta', file: '{projects}/amberx-axf/_data/beta/settings.json' },
    'demo/browser': { kind: 'browser', storageKey: 'axf.settings.demo', owner: 'app:demo' },
  },
  settings: [
    { key: 'alpha.*.use', store: 'alpha/settings', pointer: '/accounts/{1}/use', readers: ['plugin:beta'], writers: ['plugin:alpha'], mirrors: [], formerly: [{ store: 'beta/settings', pointer: '/own/{1}/use' }] },
    { key: 'alpha.limit', store: 'alpha/settings', pointer: '/limit', readers: [], writers: ['plugin:alpha'], mirrors: [] },
    { key: 'beta.**', store: 'beta/settings', pointer: '/{rest}', readers: [], writers: [], mirrors: [] },
    { key: 'demo.theme', store: 'demo/browser', pointer: '/axf.theme', readers: [], writers: ['app:demo'], mirrors: [] },
  ],
};
const o = { registry: testReg, env };
const scenario = [];
const step = async (name, fn) => { const v = await codeOf(fn); scenario.push({ name, v }); return v; };
writeFileSync(join(tmp, '.axf-console/plugins/alpha/settings.json'), JSON.stringify({ $axf: 'alpha-settings@1', accounts: { a1: { use: false } }, limit: 3 }));
writeFileSync(join(tmp, 'projects/amberx-axf/_data/beta/settings.json'), JSON.stringify({ own: { a1: { use: true } }, maxRuns: 5 }));
await step('readOwned', async () => { const r = await S.readSetting('alpha.a1.use', o); assert.equal(r.value, false); assert.equal(r.set, true); assert.equal(r.owner.store.id, 'alpha/settings'); });
await step('readUnset', async () => { const r = await S.readSetting('alpha.a2.use', o); assert.equal(r.value, undefined); assert.equal(r.set, false); });
await step('readRest', async () => { const r = await S.readSetting('beta.maxRuns', o); assert.equal(r.value, 5); });
await step('readNoOwner', () => S.readSetting('gamma.x', o));
await step('readBrowser', async () => { const r = await S.readSetting('demo.theme', o); assert.equal(r.reachable, false); assert.equal(r.owner.storeKey, 'browser:axf.settings.demo'); });
await step('writeOwned', async () => { const r = await S.writeSetting('alpha.a1.use', true, { ...o, by: 'plugin:alpha', store: 'alpha/settings' }); assert.equal(r.before, false); const d = JSON.parse(readFileSync(join(tmp, '.axf-console/plugins/alpha/settings.json'), 'utf8')); assert.equal(d.accounts.a1.use, true); assert.equal(d.limit, 3); });
await step('writeNotOwnerStore', () => S.writeSetting('alpha.a1.use', false, { ...o, store: 'beta/settings' }));
await step('writeNotOwnerBy', () => S.writeSetting('alpha.a1.use', false, { ...o, by: 'plugin:beta' }));
await step('writeNoOwner', () => S.writeSetting('gamma.x', 1, o));
await step('writeBrowser', () => S.writeSetting('demo.theme', 'dark', o));
await step('writeNew', async () => { await S.writeSetting('alpha.a2.use', true, o); const d = JSON.parse(readFileSync(join(tmp, '.axf-console/plugins/alpha/settings.json'), 'utf8')); assert.deepEqual(d.accounts, { a1: { use: true }, a2: { use: true } }); });
await step('writeRemove', async () => { await S.writeSetting('alpha.a2.use', undefined, o); const d = JSON.parse(readFileSync(join(tmp, '.axf-console/plugins/alpha/settings.json'), 'utf8')); assert.deepEqual(d.accounts, { a1: { use: true }, a2: {} }); });
await step('writeCreatesDoc', async () => { rmSync(join(tmp, 'projects/amberx-axf/_data/beta/settings.json')); await S.writeSetting('beta.maxRuns', 7, o); const d = JSON.parse(readFileSync(join(tmp, 'projects/amberx-axf/_data/beta/settings.json'), 'utf8')); assert.deepEqual(d, { maxRuns: 7 }); });
await step('assertOwnerById', () => S.assertOwner('alpha/settings', 'alpha.a1.use', o));
await step('assertOwnerByFile', () => S.assertOwner(join(tmp, '.axf-console/plugins/alpha/settings.json'), 'alpha.a1.use', o));
await step('assertNotOwnerFile', () => S.assertOwner(join(tmp, 'projects/amberx-axf/_data/beta/settings.json'), 'alpha.a1.use', o));
await step('assertNotOwnerId', () => S.assertOwner('beta/settings', 'alpha.limit', o));
await step('assertNoOwner', () => S.assertOwner('alpha/settings', 'gamma.x', o));
await step('formerPlaces', () => { const f = S.formerPlaces('alpha.a1.use', o); assert.equal(f.length, 1); assert.equal(f[0].store.id, 'beta/settings'); assert.equal(f[0].pointer, '/own/a1/use'); assert.equal(f[0].file, join(tmp, 'projects/amberx-axf/_data/beta/settings.json')); });
await step('envDir', () => { const r = S.ownerOf('alpha.limit', { registry: { ...testReg, stores: { ...testReg.stores, 'alpha/settings': { ...testReg.stores['alpha/settings'], envDir: 'ALPHA_DIR' } } }, env: { ...env, ALPHA_DIR: '/elsewhere' } }); assert.equal(r.file, '/elsewhere/settings.json'); });
await step('ambiguousThrows', () => S.ownerOf('x.a.b', { registry: { ...base(), settings: [entry({ key: 'x.*.b', pointer: '/{1}/b' }), entry({ key: 'x.a.*', pointer: '/a/{1}' })] } }));
rmSync(tmp, { recursive: true, force: true });
out.scenario = scenario;
await t('read / write scenario', () => {
  const by = Object.fromEntries(scenario.map((s) => [s.name, s.v]));
  assert.deepEqual(by, { readOwned: 'ok', readUnset: 'ok', readRest: 'ok', readNoOwner: 'no_owner', readBrowser: 'ok', writeOwned: 'ok', writeNotOwnerStore: 'not_owner', writeNotOwnerBy: 'not_owner', writeNoOwner: 'no_owner', writeBrowser: 'unreachable', writeNew: 'ok', writeRemove: 'ok', writeCreatesDoc: 'ok', assertOwnerById: 'ok', assertOwnerByFile: 'ok', assertNotOwnerFile: 'not_owner', assertNotOwnerId: 'not_owner', assertNoOwner: 'no_owner', formerPlaces: 'ok', envDir: 'ok', ambiguousThrows: 'ambiguous' });
});
out.testRegistry = testReg;

// ── fixture ──
if (WRITE) { writeFileSync(FIX, `${JSON.stringify(out, null, 1)}\n`); console.log(`wrote ${FIX}`); }
else {
  const want = JSON.parse(readFileSync(FIX, 'utf8'));
  await t('fixture current', () => { for (const k of ['stores', 'entries', 'lookups', 'patterns', 'matches', 'overlaps', 'pointers', 'registryErrors', 'scenario']) assert.ok(same(want[k], out[k]), `fixtures/settings-sources.json ${k} is stale: run check-settings-source.mjs --write`); });
}
console.log(`settings-source@1: ${n} checks passed`);
